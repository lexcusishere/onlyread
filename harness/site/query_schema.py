#!/usr/bin/env python3
"""Per-site query schema: which query keys of a write-capable request are volatile (a token, a counter, a
span id) or identify the account, session or client build (Facebook's __user, Gmail's ik, a client version)
rather than the operation, and so are folded out of the fingerprint. Nothing is folded by how a value looks. Every other key keeps its value in the fingerprint, so a
selector like ?procedure=delete can never borrow a verdict labeled for ?procedure=read.

    python3 harness/site/query_schema.py propose linkedin   # candidates from the recorded sessions
    python3 harness/site/query_schema.py build              # merge apps/*/query-schema.json into the extension

`propose` lists keys whose value took 3 or more values on one endpoint in the recordings, never the
operation-selecting names. Identifiers seen with a single value (one test account) are not proposed: find
them in the label sheet (a literal account id in a write's fingerprint; `npm run scrub` flags yours). It is a proposal: review it, and remove any key that can choose what the request
does (Gmail's act/view, LinkedIn's queryId), before it goes in apps/<app>/query-schema.json. A key that is
wrongly folded hides an operation; a key wrongly kept only sends more requests to the judge.
"""
import collections
import glob
import json
import os
import re
import sys
from urllib.parse import parse_qsl, urlsplit

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "harness", "lib"))
import fingerprint as F  # noqa: E402

GENERIC = re.compile(r"^(none|opaque|multipart|json:|json\[\]:|gql:|gql\[\]:|form:|ct:)")


def propose(app):
    vals = collections.defaultdict(lambda: collections.defaultdict(set))
    for f in glob.glob(os.path.join(ROOT, "apps", app, "sessions", "*", "decisions.jsonl")):
        for line in open(f):
            d = json.loads(line)
            if d.get("kind", "decision") != "decision" or not d.get("url") or d.get("method") in F.SAFE_METHODS:
                continue
            body = d.get("bodyFull") or d.get("bodyPreview")
            try:
                n = F.fingerprint(d["method"], d["url"], d.get("contentType"), body, body is not None)
            except Exception:
                continue
            if not GENERIC.match(n.shape):
                continue
            for k, v in parse_qsl(urlsplit(d["url"]).query, keep_blank_values=True):
                vals[n.host + n.template][k].add(v)
    out = {}
    for ep, ks in sorted(vals.items()):
        keys = sorted(k for k, vs in ks.items() if len(vs) >= 3 and k not in F.QUERY_DISCRIMINATOR_KEYS)
        if keys:
            out[ep] = keys
    print(json.dumps(out, indent=1))


def build():
    merged = {}
    for p in sorted(glob.glob(os.path.join(ROOT, "apps", "*", "query-schema.json"))):
        for ep, keys in json.load(open(p))["volatile"].items():
            merged.setdefault(ep, set()).update(keys)
    table = {ep: sorted(keys) for ep, keys in sorted(merged.items())}
    gen = os.path.join(ROOT, "extension", "src", "background", "query-schema.generated.ts")
    with open(gen, "w") as fh:
        fh.write("// Generated by harness/site/query_schema.py build from apps/*/query-schema.json. Do not edit.\n")
        fh.write("// Endpoint (host + path template) -> query keys whose values are folded out of a write's fingerprint.\n")
        fh.write("export const QUERY_VOLATILE: Record<string, readonly string[]> = " + json.dumps(table, indent=1) + ";\n")
    print(f"{gen}: {len(table)} endpoints")


if __name__ == "__main__":
    if sys.argv[1:2] == ["propose"]:
        propose(sys.argv[2])
    elif sys.argv[1:2] == ["build"]:
        build()
    else:
        sys.exit(__doc__)
